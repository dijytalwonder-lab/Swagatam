// Turns the artwork dropped into assets/festivals/<Festival name>/<anything>-<Template name>.(jpg|png|webp)
// into app art:  www/img/fest/<id>.webp  +  www/js/festival-art.js (the list the app reads).
//   - the folder name picks the festival  ("New Year" -> new-year, "Makar Sankranti" -> makar-sankranti)
//   - the text after the last "-" in the file name picks the template slot
//       Marigold -> marigold, Frame -> frame, Split -> split, Royal -> royal, Pop -> pop, Arch/Floral -> arch
// Where the title, photo and brand sit on each picture is set in www/js/skins.js (a safe default is used until then).
// Run from the project root whenever you add or change pictures:  node scripts/prepare-festivals.js
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const SRC = 'assets/festivals';
const OUT = 'www/img/fest/';
const INDEX = 'www/js/festival-art.js';

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const flat = (s) => s.toLowerCase().replace(/^happy\s+/, '').replace(/[^a-z0-9]/g, '');
const TPL = [['marigold', /marigold/], ['frame', /frame/], ['split', /split/], ['royal', /royal/], ['pop', /pop/], ['arch', /arch|floral/]];

// festival ids + names, read from the app's own list (it is an ES module, so read it as text)
const src = fs.readFileSync('www/js/festivals.js', 'utf8');
const festivals = [...src.matchAll(/\bF\('([a-z0-9-]+)',\s*(?:'((?:[^'\\]|\\.)*)'|"([^"]*)")/g)].map((m) => ({ id: m[1], name: m[2] || m[3] }));
const festivalFor = (folder) => festivals.find((f) => f.id === slug(folder) || flat(f.name) === flat(folder));

(async () => {
  if (!fs.existsSync(SRC)) throw new Error(SRC + ' not found');
  fs.mkdirSync(OUT, { recursive: true });
  const art = {}; let made = 0, kept = 0;
  const used = new Set();
  for (const dir of fs.readdirSync(SRC, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
    const fest = festivalFor(dir);
    if (!fest) { console.warn(`! "${dir}": no festival with that name - rename the folder to match the festival (e.g. "Diwali", "Holi")`); continue; }
    for (const file of fs.readdirSync(path.join(SRC, dir)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort()) {
      const base = file.replace(/\.[^.]+$/, ''), tail = base.includes('-') ? base.slice(base.lastIndexOf('-') + 1) : base;
      const hit = TPL.find(([, re]) => re.test(tail.toLowerCase()));
      if (!hit) { console.warn(`! "${dir}/${file}": cannot tell the template from "${tail}" - end the name with Marigold / Frame / Split / Royal / Pop / Arch`); continue; }
      const id = slug(dir + '-' + base), from = path.join(SRC, dir, file), to = OUT + id + '.webp';
      used.add(id + '.webp');
      if (!fs.existsSync(to) || fs.statSync(to).mtimeMs < fs.statSync(from).mtimeMs) { await sharp(from).webp({ quality: 80 }).toFile(to); made++; } else kept++;
      const m = await sharp(to).metadata();
      if (Math.abs(m.width / m.height - 9 / 16) > 0.02) console.warn(`! ${id}: ${m.width}x${m.height} is not 9:16 - it will be cropped to fill the status`);
      (art[fest.id] = art[fest.id] || []).push({ id, tpl: hit[0], label: base });
    }
  }
  // drop pictures whose source was removed
  for (const f of fs.readdirSync(OUT)) if (/\.webp$/.test(f) && !used.has(f)) fs.rmSync(OUT + f);
  fs.writeFileSync(INDEX, `// GENERATED by scripts/prepare-festivals.js from assets/festivals/ - do not edit by hand.\nexport const FESTIVAL_ART = ${JSON.stringify(art, null, 2)};\n`);
  const n = Object.values(art).reduce((a, l) => a + l.length, 0);
  console.log(`${n} festival pictures in ${Object.keys(art).length} festivals (${made} converted, ${kept} up to date)`);
  for (const [k, l] of Object.entries(art)) console.log('  ' + k + ': ' + l.map((x) => x.tpl).join(', '));
})().catch((e) => { console.error(e); process.exit(1); });
